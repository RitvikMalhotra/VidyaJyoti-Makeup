export type PhotoId = keyof typeof photos

/** srcset string for a photo, largest last. */
export function srcSet(p: Photo): string {
  return p.widths.map((w) => `/photos/${p.base}-${w}.webp ${w}w`).join(', ')
}

/** The largest variant, used as the plain `src` fallback. */
export function largest(p: Photo): string {
  return `/photos/${p.base}-${p.widths[p.widths.length - 1]}.webp`
}
